export function getWeatherLabelFromWmo(code: number): { label: string; isThunderstorm: boolean } {
  if (code === 0) return { label: 'Clear Sky', isThunderstorm: false };
  if (code === 1) return { label: 'Mainly Clear', isThunderstorm: false };
  if (code === 2) return { label: 'Partly Cloudy', isThunderstorm: false };
  if (code === 3) return { label: 'Overcast', isThunderstorm: false };
  if (code === 45 || code === 48) return { label: 'Fog / Mist', isThunderstorm: false };
  if (code >= 51 && code <= 57) return { label: 'Drizzle', isThunderstorm: false };
  if (code >= 61 && code <= 65) return { label: 'Rain', isThunderstorm: false };
  if (code === 66 || code === 67) return { label: 'Heavy Rain', isThunderstorm: false };
  if (code >= 80 && code <= 82) return { label: 'Rain Showers', isThunderstorm: false };
  if (code === 95) return { label: 'Thunderstorm', isThunderstorm: true };
  if (code === 96 || code === 99) return { label: 'Severe Thunderstorm / Hail', isThunderstorm: true };
  return { label: `Weather Code ${code}`, isThunderstorm: code >= 95 };
}
