function makeApproxPolygon(lat: number, lng: number, latRadius = 0.28, lngRadius = 0.34): [number, number][] {
  return [
    [Number((lat + latRadius).toFixed(4)), Number((lng - lngRadius * 0.6).toFixed(4))],
    [Number((lat + latRadius * 0.85).toFixed(4)), Number((lng + lngRadius * 0.7).toFixed(4))],
    [Number((lat - latRadius * 0.1).toFixed(4)), Number((lng + lngRadius).toFixed(4))],
    [Number((lat - latRadius).toFixed(4)), Number((lng + lngRadius * 0.45).toFixed(4))],
    [Number((lat - latRadius * 0.8).toFixed(4)), Number((lng - lngRadius * 0.75).toFixed(4))],
    [Number((lat + latRadius * 0.15).toFixed(4)), Number((lng - lngRadius).toFixed(4))],
  ];
}

